#!/usr/bin/env python3
"""Shared geometry-validation library for per-panel `generate_<panel_id>.py`.

Every panel generator copied from `generate_panel_template.py` imports this
module and calls `enforce(...)` from its `build_params()`. All the checks here
are FIXED — the same for every panel — so they live in one place instead of
being copied verbatim into each generator. Do NOT edit this file per panel:
panel-specific geometry (page size, element sizes, layout params,
`build_elements()`, `build_paths()`) stays in the generator; the checks and
their calibrated thresholds live here.

Stdlib-only (no venv needed). The module is staged into the panel WORKDIR next
to the generators so it imports cleanly in all three contexts that load a
generator: the panel agent running it directly, `scripts/compose.py`'s
`generate_composite.py`, and `scripts/check_params_contract.py`.
"""
from dataclasses import dataclass
import math
import sys

# ── Collision detection ──
COLLISION_MARGIN = 4

# ── Edge-endpoint snap tolerance ──
# Max distance from an edge endpoint to an element's perimeter for the
# endpoint to count as "connected". Loose enough to absorb integer
# rounding in coordinate keys but tight enough to catch endpoints that
# drift when a node moves.
ENDPOINT_SNAP_TOL = 2

# ── Minimum segment length ──
# Any polyline segment shorter than this is treated as a routing bug:
# 10–20 px stubs read as visual noise (arrowhead overlaps the source
# node, the "kink" can't be parsed by a reader). Calibrated against
# concrete examples: a 60 px terminal segment is fine, 20 px is not.
MIN_SEGMENT_LEN = 30

# ── Path-crossing budget ──
MAX_CROSSINGS_PER_PATH = 2

# ── Page-fill / dead-zone detection ──
# A coarse occupancy grid over the page flags two layout defects: (1)
# content clustered into a small region, leaving large page margins
# (check_page_fill); and (2) a large empty corner — a non-rectangular /
# L-shaped composition (check_corner_deadzones). Both waste space once
# the figure is scaled into a rectangular box in a paper (an empty corner
# is wasted column space). They are GUARDRAILS toward a compact
# rectangular layout, not hard rules: compactness is a soft property and
# intentional whitespace for visual hierarchy is legitimate, so both are
# WARNINGS (bypassable) that surface the issue and let the panel agent
# decide — fill it, or bypass if the whitespace is deliberate. Thresholds
# are starting points.
SHORT_AXIS_SUBDIV = 8    # occupancy-grid cells along the SHORTER page axis
                         # (even, so the 2x2 quadrant split lands on a cell
                         # boundary); the longer axis scales to keep cells
                         # ~square, so arrow/thin-label stamping stays isotropic.
MIN_BBOX_FILL = 0.60     # content bounding box must span >= this fraction of the page.
MIN_OVERALL_FILL = 0.30  # the corner dead-zone check only fires when the panel is at
                         # least this filled overall — a uniformly sparse panel is
                         # check_page_fill's concern, not a dead-zone imbalance.
EMPTY_CORNER_FRAC = 0.50  # a corner-anchored empty rectangle covering >= this fraction
                          # of its quadrant is flagged as a dead zone.

# Explanation appended to each empty-corner warning: why a compact
# rectangular composition matters, and when the whitespace is legitimately
# intentional (so the panel agent can make that call).
_EMPTY_CORNER_NOTE = (
    "A figure occupies a rectangular box when placed in a paper, so a large "
    "empty corner is wasted column space and gives the panel a non-rectangular, "
    "L-shaped silhouette.\n"
    "      Note: intentional white space for visual hierarchy is fine — this "
    "targets layouts that are clearly space-inefficient, not deliberate margins."
)


@dataclass
class Rect:
    name: str; x: float; y: float; w: float; h: float

    def overlaps(self, other: "Rect", margin: float = 0) -> bool:
        """True iff this rect and `other`, each inflated by `margin`, share
        any interior area (AABB overlap; edge-touching does not count)."""
        return not (
            self.x + self.w + margin <= other.x or
            other.x + other.w + margin <= self.x or
            self.y + self.h + margin <= other.y or
            other.y + other.h + margin <= self.y
        )


def check_collisions(
    elements: list[Rect], margin: float, page_w: float, page_h: float,
) -> list[str]:
    """Flag two element classes of error (empty list = OK):
      1. Out-of-bounds: any element extending past the page rectangle
         [0, 0, page_w, page_h].
      2. Overlaps: any pair of elements whose bounding boxes overlap within
         `margin`. Boxes and edge labels are both `Rect`s, so this catches a
         label sitting on top of a node as well as two nodes colliding.

    Panels register non-overlapping leaf boxes in `build_elements()` (a
    container/zone is laid out around its content, not as an overlapping
    rect), so strict pairwise overlap is the right rule — the same one the
    per-panel generators have always used."""
    errors: list[str] = []
    for e in elements:
        if e.x < 0 or e.y < 0 or e.x + e.w > page_w or e.y + e.h > page_h:
            errors.append(
                f"{e.name}: out of page bounds "
                f"[{e.x},{e.y},{e.w},{e.h}] (page {page_w}x{page_h})"
            )
    for i in range(len(elements)):
        for j in range(i + 1, len(elements)):
            a, b = elements[i], elements[j]
            if a.overlaps(b, margin):
                errors.append(
                    f"{a.name} overlaps {b.name} "
                    f"(margin={margin}): "
                    f"[{a.x},{a.y},{a.w},{a.h}] vs [{b.x},{b.y},{b.w},{b.h}]"
                )
    return errors


# ── Edges / paths ──
# Every routed edge in the panel is modelled as an EdgePath with its FULL
# polyline `points` (source endpoint, every waypoint, target endpoint)
# and an explicit `color` (hex). For ANY edge with >=1 interior
# waypoint, the template MUST emit:
#   * `points[0]`  → `<mxPoint x="{<name>_x0}" y="{<name>_y0}" as="sourcePoint"/>`
#   * `points[i]`  → entry `<mxPoint x="{<name>_x<i>}" y="{<name>_y<i>}"/>`
#                    inside `<Array as="points">` for 1 <= i <= N-1
#   * `points[-1]` → `<mxPoint x="{<name>_x<N>}" y="{<name>_y<N>}" as="targetPoint"/>`
#                    where N = len(points) - 1
#   * `color`      → the edge's `strokeColor={<name>_color}` placeholder
#
# Every polyline coordinate key (endpoints AND waypoints) MUST end in
# `_x<int>` / `_y<int>`. The Phase 4 composer offsets only keys
# matching `_x\d*$` / `_y\d*$` by the panel origin; ad-hoc names like
# `_sx`/`_tx` silently break composition (endpoints stay in panel-local
# space while waypoints shift to composite space).
#
# `source="…"`, `target="…"`, and `exitX/exitY/entryX/entryY` are
# forbidden on waypointed edges — they let drawio supply the endpoints
# from the connected shapes, decoupling the rendered polyline from
# `EdgePath.points` and silently invalidating the orthogonal-waypoint and
# crossing checks. See references/panel_agent.md + references/
# template_authoring.md. Auto-routing (orthogonalEdgeStyle) is
# forbidden separately.
@dataclass
class EdgePath:
    name: str
    color: str                    # "#1f78b4" — fills the template strokeColor placeholder
    points: list[tuple[float, float]]   # [source, *waypoints, target]; len >= 2


def check_orthogonal_waypoints(paths: list[EdgePath]) -> tuple[list[str], list[str]]:
    """Walk every path's polyline and classify each segment.

    Returns `(errors, warnings)`.

    Errors (block generation — `build_params` raises SystemExit):
      * Zero-length segment (dx == 0 and dy == 0): duplicate consecutive
        points, almost always a typo in `build_paths`.
      * Two adjacent axis-aligned segments share an axis (both
        horizontal or both vertical): the interior waypoint between
        them is collinear — a "fake" bend that contributes nothing and
        usually masks a missing waypoint.

    Warnings (printed to stderr but don't abort):
      * A segment is neither horizontal nor vertical (dx != 0 AND
        dy != 0). Diagonal segments are valid drawio but in this
        codebase they are almost always a sign that an intended
        orthogonal route is missing a waypoint. Warning, not error,
        so legitimate diagonals (tree branches, geometric illustrations)
        are not blocked.
    """
    errors: list[str] = []
    warnings: list[str] = []
    for p in paths:
        # classify each segment as 'h' (horizontal), 'v' (vertical),
        # 'd' (diagonal), or 'z' (zero-length).
        kinds: list[str] = []
        for i in range(len(p.points) - 1):
            x0, y0 = p.points[i]
            x1, y1 = p.points[i + 1]
            dx, dy = x1 - x0, y1 - y0
            if dx == 0 and dy == 0:
                errors.append(
                    f"{p.name}: segment {i}->{i+1} has zero length "
                    f"(duplicate point at ({x0}, {y0}))"
                )
                kinds.append("z")
            elif dx != 0 and dy != 0:
                warnings.append(
                    f"{p.name}: segment {i}->{i+1} is diagonal "
                    f"(dx={dx}, dy={dy}); usually means a missing "
                    f"orthogonal waypoint"
                )
                kinds.append("d")
            elif dy == 0:
                kinds.append("h")
            else:
                kinds.append("v")
        # alternation check: only meaningful between two axis-aligned
        # segments. Skip pairs involving diagonal or zero-length
        # segments (those are already flagged above).
        for i in range(len(kinds) - 1):
            a, b = kinds[i], kinds[i + 1]
            if a in ("h", "v") and b in ("h", "v") and a == b:
                errors.append(
                    f"{p.name}: waypoint {i+1} is collinear "
                    f"(segments {i} and {i+1} are both "
                    f"{'horizontal' if a == 'h' else 'vertical'})"
                )
    return errors, warnings


def check_short_segments(paths: list[EdgePath], min_len: float) -> list[str]:
    """Flag any polyline segment shorter than `min_len` (Euclidean).

    A stub of a few pixels between two waypoints — or between a waypoint
    and an endpoint — is almost always a routing bug: the arrowhead
    overlaps the connected node, the bend is too small to read as a
    bend, and the segment direction can't be visually parsed. Diagonal
    segments are measured by true Euclidean length, so this also catches
    near-coincident waypoints on a slanted route. Zero-length segments
    are already caught by `check_orthogonal_waypoints`; they're skipped
    here to avoid duplicate errors."""
    errors: list[str] = []
    for p in paths:
        for i in range(len(p.points) - 1):
            x0, y0 = p.points[i]
            x1, y1 = p.points[i + 1]
            dx, dy = x1 - x0, y1 - y0
            if dx == 0 and dy == 0:
                continue
            length = math.hypot(dx, dy)
            if length < min_len:
                errors.append(
                    f"{p.name}: segment {i}->{i+1} from ({x0}, {y0}) to "
                    f"({x1}, {y1}) is too short (length={length:.1f}, "
                    f"min={min_len})"
                )
    return errors


def _which_sides(px: float, py: float, r: Rect, tol: float) -> set[str]:
    """Return the ORIENTATIONS of `r`'s sides that (px, py) lies on within
    `tol`, restricted to the extent of the box: `'h'` if the point sits on
    the top or bottom (horizontal) edge, `'v'` if on the left or right
    (vertical) edge. A corner returns `{'h', 'v'}`; a point floating off the
    perimeter returns the empty set. Orientations (not individual sides) are
    what the graze check needs: a segment is parallel to a side iff it shares
    the side's orientation."""
    inside_x = r.x - tol <= px <= r.x + r.w + tol
    inside_y = r.y - tol <= py <= r.y + r.h + tol
    if not (inside_x and inside_y):
        return set()
    sides: set[str] = set()
    if abs(py - r.y) <= tol or abs(py - (r.y + r.h)) <= tol:
        sides.add("h")
    if abs(px - r.x) <= tol or abs(px - (r.x + r.w)) <= tol:
        sides.add("v")
    return sides


def _on_rect_perimeter(px: float, py: float, r: Rect, tol: float) -> bool:
    """True iff (px, py) lies within `tol` of one of `r`'s four sides
    AND within the extent of that side (so corners count, but points
    floating off a corner do not)."""
    return bool(_which_sides(px, py, r, tol))


def check_edge_endpoints_on_elements(
    paths: list[EdgePath], elements: list[Rect], tol: float
) -> list[str]:
    """For every edge, warn if `points[0]` (source) or `points[-1]`
    (target) does not lie on any element's perimeter within `tol`.
    Catches the "ghost connection" case where a node moved but the
    edge endpoint didn't follow, leaving the edge dangling in
    whitespace while the agent still believes it's attached.

    Warning, not error: a legitimate free-floating endpoint is rare
    but allowed (e.g. an edge whose endpoint is a label that wasn't
    registered as an element). Returns a list of warning strings."""
    warnings: list[str] = []
    for p in paths:
        if len(p.points) < 2:
            continue
        for label, idx in (("source", 0), ("target", -1)):
            px, py = p.points[idx]
            if not any(_on_rect_perimeter(px, py, r, tol) for r in elements):
                warnings.append(
                    f"{p.name}: {label} endpoint ({px}, {py}) is not "
                    f"on any element's perimeter (tol={tol}); edge may "
                    f"be dangling"
                )
    return warnings


def check_endpoint_grazes_element(
    paths: list[EdgePath], elements: list[Rect], tol: float
) -> list[str]:
    """Warn when an edge's terminal segment runs PARALLEL to a side of the
    box its endpoint sits on — a "grazing" connection.

    A clean connection meets a box perpendicular to the side it touches: the
    arrowhead points head-on into the middle of an edge. When the terminal
    segment is instead collinear with the touched side, the arrowhead skims
    along the border and reads as pointing PAST the box rather than into it.

    Corners are not exempt. At a corner the endpoint lies on both a
    horizontal and a vertical side, so any axis-aligned terminal segment is
    parallel to one of them — a corner hit is as ambiguous as an edge graze.
    The whole rule is therefore a single condition with no corner special
    case: warn iff the terminal segment's orientation is one the endpoint's
    box side shares. Diagonal terminal segments are parallel to neither axis
    and are not flagged here (they get their own warning in
    `check_orthogonal_waypoints`).

    Warning, not error: a grazing connection is occasionally unavoidable in a
    tight layout, so it is surfaced and bypassable. Endpoints that lie on no
    element yield no warning here — that dangling case is
    `check_edge_endpoints_on_elements`' job. Returns warning strings."""
    warnings: list[str] = []
    for p in paths:
        if len(p.points) < 2:
            continue
        for label, end_idx, adj_idx in (("source", 0, 1), ("target", -1, -2)):
            px, py = p.points[end_idx]
            ax, ay = p.points[adj_idx]
            dx, dy = px - ax, py - ay
            if dy == 0 and dx != 0:
                seg = "h"
            elif dx == 0 and dy != 0:
                seg = "v"
            else:
                continue  # zero-length or diagonal: handled by other checks
            for r in elements:
                if seg in _which_sides(px, py, r, tol):
                    edge = "top/bottom" if seg == "h" else "left/right"
                    warnings.append(
                        f"{p.name}: {label} endpoint ({px}, {py}) meets "
                        f"{r.name} running parallel to its {edge} edge "
                        f"(grazing/corner hit); route the arrow to approach "
                        f"the box perpendicular to the side it touches"
                    )
    return warnings


def _segments_intersect(
    a0: tuple[float, float], a1: tuple[float, float],
    b0: tuple[float, float], b1: tuple[float, float],
) -> bool:
    """True iff segments a0-a1 and b0-b1 either (a) strictly cross
    (proper X-intersection) or (b) overlap along a collinear stretch.
    T-junctions (one segment's endpoint on the other's interior) are
    deliberately NOT counted — those represent intentional same-color
    fan-in merges. Mutually-shared endpoints (paths meeting at a node)
    are also excluded."""
    def cross(ox, oy, px, py, qx, qy):
        return (px - ox) * (qy - oy) - (py - oy) * (qx - ox)

    def on_seg(p, q, r):
        # assumes p, q, r collinear; tests whether r lies on segment p-q
        return (min(p[0], q[0]) <= r[0] <= max(p[0], q[0]) and
                min(p[1], q[1]) <= r[1] <= max(p[1], q[1]))

    def shared_endpoint(pt):
        return pt in (a0, a1) and pt in (b0, b1)

    d1 = cross(b0[0], b0[1], b1[0], b1[1], a0[0], a0[1])
    d2 = cross(b0[0], b0[1], b1[0], b1[1], a1[0], a1[1])
    d3 = cross(a0[0], a0[1], a1[0], a1[1], b0[0], b0[1])
    d4 = cross(a0[0], a0[1], a1[0], a1[1], b1[0], b1[1])

    # Proper crossing: the segments strictly straddle each other.
    if ((d1 > 0 and d2 < 0) or (d1 < 0 and d2 > 0)) and \
       ((d3 > 0 and d4 < 0) or (d3 < 0 and d4 > 0)):
        return True

    # All four collinear → check 1D overlap (any interior overlap counts;
    # touching only at a mutually-shared endpoint does not).
    if d1 == 0 and d2 == 0 and d3 == 0 and d4 == 0:
        for r in (b0, b1):
            if on_seg(a0, a1, r) and not shared_endpoint(r):
                return True
        for r in (a0, a1):
            if on_seg(b0, b1, r) and not shared_endpoint(r):
                return True
        return False

    # T-junctions (an endpoint of one segment on the interior of the
    # other) are intentionally NOT flagged: same-color T-junctions are
    # the standard "fan-in" pattern for multiple sources merging onto a
    # shared point on another path (e.g. several gradient flows summing
    # into one update). Those distinct sources can't be collapsed into a
    # single polyline, and same-color signals "same kind of thing
    # flowing together". Accidental endpoints that drift onto an
    # unrelated edge's interior are caught instead by
    # `check_edge_endpoints_on_elements` (which flags endpoints not on a
    # registered node perimeter).

    return False


def find_path_crossings(paths: list[EdgePath]) -> dict[str, list[dict]]:
    """Return every pairwise segment crossing, keyed by path name.

    Both same-color and different-color crossings are included; callers
    filter as needed (`check_path_crossings` keeps only same-color
    pairs). Shared endpoints (paths meeting at a node) are not
    crossings and are excluded. Each crossing appears twice — once
    under each participating path — so `result[name]` lists everything
    `name` runs into.

    Each record has shape:
        {
            "segment":       (i, i+1),     # this path's segment
            "color":         "#…",          # this path's color
            "other":         "<name>",      # other path's name
            "other_segment": (j, j+1),     # other path's segment
            "other_color":   "#…",          # other path's color
        }

    Paths with zero crossings are omitted from the dict (no empty
    lists). Geometry rules (proper crossings, collinear overlap,
    T-junction and shared-endpoint exemptions) are delegated to
    `_segments_intersect`."""
    crossings: dict[str, list[dict]] = {}
    n = len(paths)
    for i in range(n):
        a = paths[i]
        for j in range(i + 1, n):
            b = paths[j]
            for si in range(len(a.points) - 1):
                a0, a1 = a.points[si], a.points[si + 1]
                for sj in range(len(b.points) - 1):
                    b0, b1 = b.points[sj], b.points[sj + 1]
                    if not _segments_intersect(a0, a1, b0, b1):
                        continue
                    crossings.setdefault(a.name, []).append({
                        "segment": (si, si + 1),
                        "color": a.color,
                        "other": b.name,
                        "other_segment": (sj, sj + 1),
                        "other_color": b.color,
                    })
                    crossings.setdefault(b.name, []).append({
                        "segment": (sj, sj + 1),
                        "color": b.color,
                        "other": a.name,
                        "other_segment": (si, si + 1),
                        "other_color": a.color,
                    })
    return crossings


def check_path_crossings(paths: list[EdgePath]) -> list[str]:
    """Pairwise segment-intersection check across all paths. Returns a
    list of error strings (empty = OK).

    Two error classes:
      1. Same-color crossings (different colors are allowed to cross,
         per `references/panel_agent.md`). Proper X-crossings and
         collinear overlap count; shared endpoints at a common node
         and T-junctions (endpoint on another path's interior) do NOT
         — same-color T-junctions are the standard fan-in merge.
      2. Any path involved in strictly more than
         `MAX_CROSSINGS_PER_PATH` (= 2) crossings, regardless of color.
         Even allowed (different-color) crossings cost legibility, and a
         single arrow tangled through 3+ others is almost always a
         routing bug rather than an intentional dense layout."""
    crossings = find_path_crossings(paths)
    errors: list[str] = []

    seen: set[tuple] = set()
    for name, records in crossings.items():
        for r in records:
            if r["color"] != r["other_color"]:
                continue
            key = tuple(sorted([
                (name, r["segment"]),
                (r["other"], r["other_segment"]),
            ]))
            if key in seen:
                continue
            seen.add(key)
            (n1, s1), (n2, s2) = key
            errors.append(
                f"{n1} segment {s1[0]}->{s1[1]} crosses {n2} segment "
                f"{s2[0]}->{s2[1]}; both color {r['color']}"
            )

    for name, records in crossings.items():
        if len(records) > MAX_CROSSINGS_PER_PATH:
            others = sorted({r["other"] for r in records})
            errors.append(
                f"{name} has {len(records)} crossings (> "
                f"{MAX_CROSSINGS_PER_PATH}) with: {', '.join(others)}; "
                f"reroute to reduce tangling"
            )

    return errors


def _grid_dims(page_w: float, page_h: float) -> tuple[int, int]:
    """Occupancy-grid resolution: SHORT_AXIS_SUBDIV cells along the shorter
    page axis, the longer axis scaled to keep cells ~square. Both rounded
    to even so the 2x2 quadrant split lands on a cell boundary. Deriving
    the cell size from the SHORT side (not a fixed pixel target) keeps the
    resolution scale-invariant: the constrained dimension always gets
    SHORT_AXIS_SUBDIV cells, whatever the page aspect."""
    cell = min(page_w, page_h) / SHORT_AXIS_SUBDIV
    nx = max(2, round(page_w / cell / 2) * 2)
    ny = max(2, round(page_h / cell / 2) * 2)
    return nx, ny


def _occupancy_grid(
    elements: list[Rect], paths: list[EdgePath],
    page_w: float, page_h: float, nx: int, ny: int,
) -> list[list[bool]]:
    """Rasterize all content into an nx*ny boolean grid, indexed
    `grid[j][i]` (j = row from the top, i = column from the left).

    Handles every content type uniformly:
      * Rects — boxes AND text labels (build_elements() returns edge
        labels too) — stamp their whole area as filled.
      * EdgePaths — arrows — stamp every cell their polyline passes
        through, so a thin arrow still marks the region it crosses as
        live (a corner an arrow runs through is not a dead zone). Cells
        are ~square, so this line-stamping is direction-independent.

    Because the grid is a boolean union, overlapping boxes/labels do not
    double-count."""
    grid = [[False] * nx for _ in range(ny)]
    cw, ch = page_w / nx, page_h / ny

    def cell(x: float, y: float) -> tuple[int, int]:
        i = min(nx - 1, max(0, int(x // cw)))
        j = min(ny - 1, max(0, int(y // ch)))
        return i, j

    for r in elements:
        i0, j0 = cell(r.x, r.y)
        i1, j1 = cell(r.x + r.w, r.y + r.h)
        for j in range(j0, j1 + 1):
            for i in range(i0, i1 + 1):
                grid[j][i] = True

    step = min(cw, ch) / 2 or 1.0
    for p in paths:
        pts = p.points
        for (ax, ay), (bx, by) in zip(pts, pts[1:]):
            n = int(math.hypot(bx - ax, by - ay) / step) + 1
            for s in range(n + 1):
                t = s / n
                i, j = cell(ax + t * (bx - ax), ay + t * (by - ay))
                grid[j][i] = True
    return grid


def check_page_fill(
    elements: list[Rect], paths: list[EdgePath], page_w: float, page_h: float,
) -> list[str]:
    """Warn when the content bounding box spans less than MIN_BBOX_FILL of
    the page. Content clustered into a small region becomes dead space
    when the composer tiles this panel at its page_w x page_h slot — so a
    panel that fails to fill its own PAGE box is where composite dead
    zones start. The bbox includes arrow endpoints, so an edge routed out
    to the margin legitimately counts as content reaching there.

    A single robust, position-independent signal — deliberately NOT
    per-edge margins: the composite is cropped to its content bbox on
    export, so a panel's *outer* margins get cropped harmlessly and the
    panel cannot know which of its edges will be outer vs. abut a
    neighbour. One-sided emptiness is check_corner_deadzones' job."""
    xs: list[float] = []
    ys: list[float] = []
    for r in elements:
        xs.extend((r.x, r.x + r.w))
        ys.extend((r.y, r.y + r.h))
    for p in paths:
        for x, y in p.points:
            xs.append(x)
            ys.append(y)
    if not xs:
        return []
    fill = ((max(xs) - min(xs)) * (max(ys) - min(ys))) / (page_w * page_h)
    if fill < MIN_BBOX_FILL:
        return [
            f"content bounding box spans {fill:.0%} of the page "
            f"(< {MIN_BBOX_FILL:.0%}); content is clustered in a small region "
            f"and becomes dead space when the composer tiles this panel — "
            f"spread elements to fill PAGE_W x PAGE_H"
        ]
    return []


def _corner_empty_area(grid: list[list[bool]], nx: int, ny: int) -> dict[str, int]:
    """For each of the four corners, the area (in cells) of the largest
    empty axis-aligned rectangle anchored at that corner, grown inward
    until it hits an occupied cell, capped at the midlines (nx//2, ny//2).

    The rectangle is grown by a min-run scan: a rectangle spanning rows
    0..j (anchored at the top-left) can be no wider than the narrowest
    leading-empty run among those rows, so its area is `(j+1) * min_run`,
    maximised over j. Measuring a corner-anchored *empty rectangle* — not
    a fixed quadrant's occupancy — is what makes the signal survive a
    quadrant that is half-full-half-empty (content on one side, dead zone
    on the other averages to ~50% and would slip a raw occupancy test).
    The other three corners reuse the same scan on a reflected grid."""
    hx, hy = nx // 2, ny // 2

    def top_left(g: list[list[bool]]) -> int:
        best, min_run = 0, hx
        for j in range(hy):
            run = 0
            while run < hx and not g[j][run]:
                run += 1
            min_run = min(min_run, run)
            if min_run == 0:
                break  # corner column blocked at this row -> cannot grow taller
            best = max(best, (j + 1) * min_run)
        return best

    def flip_h(g: list[list[bool]]) -> list[list[bool]]:
        return [row[::-1] for row in g]

    def flip_v(g: list[list[bool]]) -> list[list[bool]]:
        return g[::-1]

    return {
        "top-left": top_left(grid),
        "top-right": top_left(flip_h(grid)),
        "bottom-left": top_left(flip_v(grid)),
        "bottom-right": top_left(flip_v(flip_h(grid))),
    }


def check_corner_deadzones(
    elements: list[Rect], paths: list[EdgePath], page_w: float, page_h: float,
) -> list[str]:
    """Flag each corner holding a large empty region — a corner-anchored
    empty rectangle covering >= EMPTY_CORNER_FRAC of its quadrant while the
    panel is otherwise filled (overall >= MIN_OVERALL_FILL). One warning
    per offending corner.

    A guardrail toward a compact, rectangular composition, not a hard rule:
    a non-rectangular (L-shaped) silhouette wastes column space once the
    figure is scaled into a paper, but a large empty corner can also be
    legitimate visual hierarchy. So each large corner is surfaced with a
    note and the panel agent decides — fill it to stay rectangular, or
    --bypass-warnings if the whitespace is deliberate. The overall-fill
    guard keeps this from double-firing with check_page_fill on a sparse
    panel; central voids (not corner-anchored) are out of scope."""
    nx, ny = _grid_dims(page_w, page_h)
    grid = _occupancy_grid(elements, paths, page_w, page_h, nx, ny)
    overall = sum(sum(row) for row in grid) / (nx * ny)
    if overall < MIN_OVERALL_FILL:
        return []
    quad = (nx // 2) * (ny // 2)
    out: list[str] = []
    for corner, empty in _corner_empty_area(grid, nx, ny).items():
        frac = empty / quad
        if frac >= EMPTY_CORNER_FRAC:
            out.append(
                f"{corner} corner is a large empty region ({frac:.0%} of its quadrant, "
                f"grown to the midlines); content is clustered away from it. "
                f"{_EMPTY_CORNER_NOTE}\n"
                f"      Fill the {corner} corner to keep the composition rectangular, "
                f"OR bypass if this whitespace is deliberate and reads as intentional."
            )
    return out


def run_checks(
    elements: list[Rect], paths: list[EdgePath], page_w: float, page_h: float,
) -> tuple[list[str], list[str]]:
    """Run every panel geometry check and return `(errors, warnings)`.

    Errors block generation unconditionally; warnings block unless bypassed
    (see `enforce`). This is the single place the individual checks are
    wired together, so a panel's `build_params()` never re-implements the
    assembly — it calls `enforce(...)`."""
    errors = check_collisions(elements, COLLISION_MARGIN, page_w, page_h)
    ortho_errors, ortho_warnings = check_orthogonal_waypoints(paths)
    errors += ortho_errors
    errors += check_short_segments(paths, MIN_SEGMENT_LEN)
    errors += check_path_crossings(paths)
    warnings = ortho_warnings
    warnings += check_edge_endpoints_on_elements(paths, elements, ENDPOINT_SNAP_TOL)
    warnings += check_endpoint_grazes_element(paths, elements, ENDPOINT_SNAP_TOL)
    warnings += check_page_fill(elements, paths, page_w, page_h)
    warnings += check_corner_deadzones(elements, paths, page_w, page_h)
    return errors, warnings


def enforce(
    elements: list[Rect], paths: list[EdgePath],
    page_w: float, page_h: float, bypass_warnings: bool = False,
) -> None:
    """Run all checks, print any warnings/errors to stderr, and abort
    (`SystemExit(1)`) on any error — or on any warning unless
    `bypass_warnings=True`. Called from every panel's `build_params()`.

    Errors are never bypassable. Warnings block too, unless
    `bypass_warnings=True` (surfaced as `--bypass-warnings` on the CLI) —
    pass it ONLY when every warning above has been reviewed and each one
    has a valid reason to be bypassed."""
    errors, warnings = run_checks(elements, paths, page_w, page_h)
    for w in warnings:
        print(f"WARNING: {w}", file=sys.stderr)
    if errors:
        for e in errors:
            print(e, file=sys.stderr)
        raise SystemExit(1)
    if warnings and not bypass_warnings:
        print(
            f"BLOCKED: {len(warnings)} warning(s) above and no errors. "
            "Generation does not run while warnings remain. Re-run with "
            "--bypass-warnings ONLY if you have reviewed every single "
            "warning above and each one has a valid reason to be bypassed.",
            file=sys.stderr,
        )
        raise SystemExit(1)
